import { execFileSync } from "node:child_process";
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { GALLERY_SAMPLE_RESUME } from "../src/components/marketing/sample-resume";
import { withTemplateDefaults } from "../src/features/resume-editor/lib/template-defaults";
import type { TemplateType } from "../src/features/resume-editor/types";
import { TEMPLATE_CONFIGS } from "../src/features/resume-editor/types";
import { resumeToTypstJson } from "../src/lib/typst/serialize";
import { TYPST, TYPST_COMPILE_FLAGS, TYPST_PROBLEM } from "./helpers/typst-cli";

/**
 * The marketing gallery is generated by the product, not drawn beside it.
 *
 * The Templates section on the landing page used to be three text cards with a schematic
 * note. The real thing is nearly free: `resumeToTypstJson` + `sections.typ` +
 * `<template>.typ` is exactly what the export button runs, and Typst emits SVG. Compiling
 * it once, at test time, produces a page-accurate preview of each template with no new
 * rendering code and no screenshot to fall out of date.
 *
 * ## Generated here, not in the browser
 *
 * `public/templates/*.svg` are committed build artefacts. Nothing on the marketing page
 * loads the Typst WASM: it is a `static export`, the gallery must stay fast, and a
 * marketing page that depends on a CDN compiler to show its own screenshots is a page
 * that is blank when the CDN is.
 *
 * ## Staleness is a test failure
 *
 * This test compiles each template and compares the result with the committed file. If
 * someone edits `sections.typ` or a template and does not regenerate, CI fails and says
 * so. Set `UPDATE_TEMPLATE_GALLERY=1` to regenerate:
 *
 *     npm run templates:render
 *
 * It fails when the `typst` binary is unavailable, the same rule `typst-compile.test.ts`
 * follows: CI installs the compiler, so a missing one is a broken gate rather than a
 * gallery that might be fine. See `test/helpers/typst-cli.ts`.
 */

const ROOT = resolve(process.cwd());
const TEMPLATE_DIR = join(ROOT, "src/features/resume-editor/typst_templates");
const OUT_DIR = join(ROOT, "public/templates");
const UPDATE = process.env.UPDATE_TEMPLATE_GALLERY === "1";

/** One page of one archetype, as SVG. */
function renderFirstPage(template: TemplateType, dir: string): string {
	const sections = readFileSync(join(TEMPLATE_DIR, "sections.typ"), "utf8");
	const config = TEMPLATE_CONFIGS[template];
	// `compact` shares `standard.typ`; its specimen differs because of the settings
	// defaults applied below, which is exactly what the config variant means.
	const body = readFileSync(
		join(TEMPLATE_DIR, `${config.sourceFile}.typ`),
		"utf8",
	);

	// Each specimen is the archetype as selected, not the sample's own settings with a
	// different file: density is half of what distinguishes these documents.
	const metadata = GALLERY_SAMPLE_RESUME.metadata;
	const sample = metadata
		? {
				...GALLERY_SAMPLE_RESUME,
				metadata: {
					...metadata,
					settings: withTemplateDefaults(template, metadata.settings),
				},
			}
		: GALLERY_SAMPLE_RESUME;

	writeFileSync(join(dir, "sample.json"), resumeToTypstJson(sample));
	const sourcePath = join(dir, `${template}.typ`);
	writeFileSync(
		sourcePath,
		`#let data = json("sample.json")\n${sections}\n\n${body}`,
	);

	const [command, prefix] = TYPST as readonly [string, string[]];
	// No page pattern: the sample is one page, and `typst` writes a single-page SVG to
	// the exact filename. A pattern like `{0p}` is not expanded when the command runs
	// through `cmd.exe` on Windows, which produces a file literally named `x{0p}.svg`.
	const svgPath = join(dir, `${template}.svg`);
	execFileSync(
		command,
		[
			...prefix,
			"compile",
			...TYPST_COMPILE_FLAGS,
			"--format",
			"svg",
			sourcePath,
			svgPath,
		],
		{ cwd: dir, stdio: "pipe", shell: process.platform === "win32" },
	);

	return readFileSync(svgPath, "utf8");
}

const TEMPLATE_IDS = Object.keys(TEMPLATE_CONFIGS) as TemplateType[];

/**
 * A platform-independent signature of a rendered page.
 *
 * Byte equality is **not** portable and never was — it only looked portable because this
test skipped in CI (it has no `typst` binary), so the committed files had only ever been
compared against a render on the machine that produced them. Typst emits every glyph as
an SVG `<symbol>` whose path data is computed with floating point, and a Linux and a
Windows build of the same 0.14.2 disagree in the last digits; the symbol id is a hash of
that path, so every `<use>` reference changes too. The geometry does not: every
`transform` and every glyph advance is identical (verified against the failing CI run —
same positions, different outlines).

The gallery's purpose is to be a faithful, current picture of each template, and what a
template edit changes is *layout*. So the comparison keeps the whole transform tree, the
fills, and every glyph's advance, and drops only the glyph outlines and their hashed ids.
 */
function layoutSignature(svg: string): string {
	return svg
		.replace(/<symbol[\s\S]*?<\/symbol>/g, "<symbol/>")
		.replace(/xlink:href="#[^"]*"/g, 'xlink:href="#"')
		.replace(/\s+/g, " ")
		.trim();
}

describe("the template gallery is rendered by the real pipeline", () => {
	const dir = mkdtempSync(join(tmpdir(), "br-gallery-"));
	if (UPDATE) mkdirSync(OUT_DIR, { recursive: true });

	it.each(TEMPLATE_IDS)(
		"%s has a committed first page that matches the current templates",
		(template) => {
			expect(TYPST, TYPST_PROBLEM).not.toBeNull();
			const actual = renderFirstPage(template, dir);
			const file = join(OUT_DIR, `${template}.svg`);

			// A page, not a blank card: the sample has a name, two jobs and three skill
			// groups. An empty template would produce a few hundred bytes of <svg> shell.
			expect(actual.length).toBeGreaterThan(4000);

			if (UPDATE) {
				writeFileSync(file, actual);
				return;
			}

			expect(
				existsSync(file),
				`public/templates/${template}.svg is missing. Run: npm run templates:render`,
			).toBe(true);

			// Same compiler, same document, same layout. Comparing the signature rather than
			// the bytes keeps the gate portable; see `layoutSignature` for why byte equality
			// cannot be.
			expect(
				layoutSignature(readFileSync(file, "utf8")),
				`public/templates/${template}.svg is stale. Run: npm run templates:render`,
			).toBe(layoutSignature(actual));
		},
		120_000,
	);
});
